#include "textflag.h"
// Eight contiguous token rows become eight column vectors.
TEXT ·pack8AVX2(SB), NOSPLIT, $0-32
 MOVQ input+0(FP),DI
 MOVQ packed+8(FP),SI
 MOVQ cols+16(FP),CX
 MOVQ CX,R8
 SHLQ $2,R8
 MOVQ tokens+24(FP),R9
 SHLQ $2,R9
pack_loop:
 MOVQ DI,AX
 VMOVUPS (AX),Y8
 ADDQ R8,AX
 VMOVUPS (AX),Y9
 ADDQ R8,AX
 VMOVUPS (AX),Y10
 ADDQ R8,AX
 VMOVUPS (AX),Y11
 ADDQ R8,AX
 VMOVUPS (AX),Y12
 ADDQ R8,AX
 VMOVUPS (AX),Y13
 ADDQ R8,AX
 VMOVUPS (AX),Y14
 ADDQ R8,AX
 VMOVUPS (AX),Y15
 VUNPCKLPS Y9,Y8,Y0
 VUNPCKHPS Y9,Y8,Y1
 VUNPCKLPS Y11,Y10,Y2
 VUNPCKHPS Y11,Y10,Y3
 VUNPCKLPS Y13,Y12,Y4
 VUNPCKHPS Y13,Y12,Y5
 VUNPCKLPS Y15,Y14,Y6
 VUNPCKHPS Y15,Y14,Y7
 VSHUFPS $0x44,Y2,Y0,Y8
 VSHUFPS $0xee,Y2,Y0,Y9
 VSHUFPS $0x44,Y3,Y1,Y10
 VSHUFPS $0xee,Y3,Y1,Y11
 VSHUFPS $0x44,Y6,Y4,Y12
 VSHUFPS $0xee,Y6,Y4,Y13
 VSHUFPS $0x44,Y7,Y5,Y14
 VSHUFPS $0xee,Y7,Y5,Y15
 VPERM2F128 $0x20,Y12,Y8,Y0
 VPERM2F128 $0x20,Y13,Y9,Y1
 VPERM2F128 $0x20,Y14,Y10,Y2
 VPERM2F128 $0x20,Y15,Y11,Y3
 VPERM2F128 $0x31,Y12,Y8,Y4
 VPERM2F128 $0x31,Y13,Y9,Y5
 VPERM2F128 $0x31,Y14,Y10,Y6
 VPERM2F128 $0x31,Y15,Y11,Y7
 VMOVUPS Y0,(SI)
 ADDQ R9,SI
 VMOVUPS Y1,(SI)
 ADDQ R9,SI
 VMOVUPS Y2,(SI)
 ADDQ R9,SI
 VMOVUPS Y3,(SI)
 ADDQ R9,SI
 VMOVUPS Y4,(SI)
 ADDQ R9,SI
 VMOVUPS Y5,(SI)
 ADDQ R9,SI
 VMOVUPS Y6,(SI)
 ADDQ R9,SI
 VMOVUPS Y7,(SI)
 ADDQ R9,SI
 ADDQ $32,DI
 SUBQ $8,CX
 JNZ pack_loop
 VZEROUPPER
 RET
