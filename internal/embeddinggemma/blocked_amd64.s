// Eight decoded weight rows times eight packed activation columns. FP32
// accumulation, no activation quantisation and no horizontal reduction.
TEXT ·blockedRowsAVX2(SB), NOSPLIT, $0-40
 MOVQ weights+0(FP), R12
 MOVQ packed+8(FP), R13
 MOVQ output+16(FP), R8
 MOVQ cols+24(FP), R9
 SHLQ $2, R9
 MOVQ tokens+32(FP), R10
 SHLQ $2, R10
 LEAQ (R9)(R9*1), R11
 LEAQ (R11)(R9*1), AX
 MOVQ $4, BX
 IMULQ R9, BX
 MOVQ $5, R14
 IMULQ R9, R14
 MOVQ $6, R15
 IMULQ R9, R15
 MOVQ $7, R11
 IMULQ R9, R11
 XORQ CX, CX
bl_token:
 MOVQ R12, SI
 MOVQ CX,DI
 IMULQ cols+24(FP),DI
 ADDQ R13,DI
 MOVQ cols+24(FP), DX
 VXORPS Y8, Y8, Y8
 VXORPS Y9, Y9, Y9
 VXORPS Y10, Y10, Y10
 VXORPS Y11, Y11, Y11
 VXORPS Y12,Y12,Y12
 VXORPS Y13,Y13,Y13
 VXORPS Y14,Y14,Y14
 VXORPS Y15,Y15,Y15
bl_col:
 VMOVUPS (DI), Y0
 VBROADCASTSS 0(SI), Y1
 VFMADD231PS Y0, Y1, Y8
 VBROADCASTSS (SI)(R9*1), Y2
 VFMADD231PS Y0, Y2, Y9
 VBROADCASTSS (SI)(R9*2), Y3
 VFMADD231PS Y0, Y3, Y10
 VBROADCASTSS (SI)(AX*1), Y4
 VFMADD231PS Y0, Y4, Y11
 VBROADCASTSS (SI)(BX*1), Y1
 VFMADD231PS Y0, Y1, Y12
 VBROADCASTSS (SI)(R14*1),Y1
 VFMADD231PS Y0, Y1, Y13
 VBROADCASTSS (SI)(R15*1),Y1
 VFMADD231PS Y0, Y1, Y14
 VBROADCASTSS (SI)(R11*1),Y1
 VFMADD231PS Y0, Y1, Y15
 ADDQ $4, SI
 ADDQ $32, DI
 DECQ DX
 JNZ bl_col
 LEAQ (R8)(CX*1), DI
 VMOVUPS Y8, (DI)
 VMOVUPS Y9, (DI)(R10*1)
 LEAQ (DI)(R10*2), SI
 VMOVUPS Y10, (SI)
 VMOVUPS Y11, (SI)(R10*1)
 LEAQ (SI)(R10*2),DI
 VMOVUPS Y12,(DI)
 VMOVUPS Y13,(DI)(R10*1)
 ADDQ R10,DI
 ADDQ R10,DI
 VMOVUPS Y14,(DI)
 VMOVUPS Y15,(DI)(R10*1)
 ADDQ $32,CX
 CMPQ CX, R10
 JL bl_token
 VZEROUPPER
 RET

