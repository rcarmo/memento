// One call per row: process both nibble planes together, extracting scale/min
// once per 32-value group. All loads remain inside a 144-byte Q4_K block.
TEXT ·q4RowAVX2(SB), NOSPLIT, $0-36
 MOVQ raw+0(FP), SI
 MOVQ x+8(FP), DI
 MOVQ blocks+16(FP), CX
 MOVQ halfTable+24(FP), R8
 VPCMPEQD Y6, Y6, Y6
 VPSRLD $28, Y6, Y6
 VXORPS Y15, Y15, Y15
q4r_block:
 MOVWLZX (SI), AX
 VBROADCASTSS (R8)(AX*4), Y8
 MOVWLZX 2(SI), AX
 VBROADCASTSS (R8)(AX*4), Y9
 LEAQ 16(SI), R9
 XORQ R10, R10
q4r_pair:
 CMPQ R10, $4
 JGE q4r_upper_scales
 MOVBLZX 4(SI)(R10*1), AX
 ANDL $63, AX
 MOVBLZX 8(SI)(R10*1), BX
 ANDL $63, BX
 MOVBLZX 5(SI)(R10*1), R11
 ANDL $63, R11
 MOVBLZX 9(SI)(R10*1), R12
 ANDL $63, R12
 JMP q4r_scales_ready
q4r_upper_scales:
 MOVBLZX 8(SI)(R10*1), AX
 ANDL $15, AX
 MOVBLZX (SI)(R10*1), DX
 SHRL $6, DX
 SHLL $4, DX
 ORL DX, AX
 MOVBLZX 8(SI)(R10*1), BX
 SHRL $4, BX
 MOVBLZX 4(SI)(R10*1), DX
 SHRL $6, DX
 SHLL $4, DX
 ORL DX, BX
 MOVBLZX 9(SI)(R10*1), R11
 ANDL $15, R11
 MOVBLZX 1(SI)(R10*1), DX
 SHRL $6, DX
 SHLL $4, DX
 ORL DX, R11
 MOVBLZX 9(SI)(R10*1), R12
 SHRL $4, R12
 MOVBLZX 5(SI)(R10*1), DX
 SHRL $6, DX
 SHLL $4, DX
 ORL DX, R12
q4r_scales_ready:
 VMOVD AX, X0
 VCVTDQ2PS X0, X0
 VBROADCASTSS X0, Y2
 VMULPS Y8, Y2, Y2
 VMOVD BX, X0
 VCVTDQ2PS X0, X0
 VBROADCASTSS X0, Y3
 VMULPS Y9, Y3, Y3
 VMOVD R11, X0
 VCVTDQ2PS X0, X0
 VBROADCASTSS X0, Y4
 VMULPS Y8, Y4, Y4
 VMOVD R12, X0
 VCVTDQ2PS X0, X0
 VBROADCASTSS X0, Y5
 VMULPS Y9, Y5, Y5
 XORQ DX, DX
q4r_values:
 VPMOVZXBD (R9)(DX*1), Y0
 VPSRLD $4, Y0, Y1
 VPAND Y6, Y0, Y0
 VCVTDQ2PS Y0, Y0
 VMULPS Y2, Y0, Y0
 VSUBPS Y3, Y0, Y0
 VCVTDQ2PS Y1, Y1
 VMULPS Y4, Y1, Y1
 VSUBPS Y5, Y1, Y1
 VMULPS (DI)(DX*4), Y0, Y0
 VMULPS 128(DI)(DX*4), Y1, Y1
 VADDPS Y0, Y15, Y15
 VADDPS Y1, Y15, Y15
 ADDQ $8, DX
 CMPQ DX, $32
 JL q4r_values
 ADDQ $32, R9
 ADDQ $256, DI
 ADDQ $2, R10
 CMPQ R10, $8
 JL q4r_pair
 ADDQ $144, SI
 DECQ CX
 JNZ q4r_block
 VEXTRACTF128 $1, Y15, X1
 VADDPS X1, X15, X0
 VHADDPS X0, X0, X0
 VHADDPS X0, X0, X0
 VMOVSS X0, ret+32(FP)
 VZEROUPPER
 RET

