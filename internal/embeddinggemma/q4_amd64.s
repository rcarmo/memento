TEXT ·q4GroupSSE2(SB), NOSPLIT, $0-36
 MOVQ q+0(FP), SI
 MOVQ x+8(FP), DI
 MOVSS scale+16(FP), X4
 SHUFPS $0, X4, X4
 MOVSS minimum+20(FP), X5
 SHUFPS $0, X5, X5
 PCMPEQL X6, X6
 PSRLL $28, X6
 PXOR X7, X7
 PXOR X8, X8
 MOVBLZX high+24(FP), AX
 MOVQ $8, CX
q4s_loop:
 MOVL (SI), AX
 MOVD AX, X0
 CMPB high+24(FP), $0
 JE q4s_low
 PSRLW $4, X0
q4s_low:
 PUNPCKLBW X7, X0
 PUNPCKLWL X7, X0
 PAND X6, X0
 CVTPL2PS X0, X0
 MULPS X4, X0
 SUBPS X5, X0
 MOVUPS (DI), X1
 MULPS X1, X0
 ADDPS X0, X8
 ADDQ $4, SI
 ADDQ $16, DI
 DECQ CX
 JNZ q4s_loop
 MOVAPS X8, X0
 MOVAPS X0, X1
 SHUFPS $0x4e, X1, X1
 ADDPS X1, X0
 MOVAPS X0, X1
 SHUFPS $0xb1, X1, X1
 ADDPS X1, X0
 MOVSS X0, ret+32(FP)
 RET

